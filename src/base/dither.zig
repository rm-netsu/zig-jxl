/// The final float -> integer sample conversion of the output stage.
/// `bits` is the output bit depth (<= 8 dithers like libjxl's u8 path,
/// 9..16 uses the plain u16 path). `(x, y)` are the global pixel
/// coordinates, `c` the output channel index (color channels first,
/// alpha last); `v` the pipeline float value.
///
/// The 8-bit path is `v * mul + dither` computed as a *fused* multiply-add:
/// the reference compiles `Mul(v, mul); Add(v, dither)` into a single FMA
/// (GCC's default fp-contract), so the two-rounding evaluation differs by
/// one ULP exactly at the tie cases.
pub fn sampleToUint(v_in: f32, mul: f32, bits: u6, x: usize, y: usize, c: usize) u32 {
    var v: f32 = undefined;
    if (bits <= 8) {
        // Ordered dithering, matching MakeUnsigned for u8 (fused).
        const x_off = (x + c * 23) % 32;
        const y_off = (y + c * 13) % 32;
        const pos = y_off * 48 + x_off;
        v = @mulAdd(f32, v_in, mul, kDither[pos]);
    } else {
        v = v_in * mul;
    }
    // Clamp(v, Zero, mul): NaN maps to 0 through the min/max chain.
    if (v != v) return 0;
    v = std.math.clamp(v, 0.0, mul);
    const iv = float_convert.nearestEven(v);
    return @intCast(std.math.clamp(iv, 0, @as(i32, @intFromFloat(mul))));
}

test "dither table dims and range" {
    try std.testing.expectEqual(@as(usize, 48 * 32), kDither.len);
    var sum: f32 = 0;
    for (kDither) |d| {
        try std.testing.expect(d > -0.5 and d < 0.5);
        sum += d;
    }
    // Scaled to have an average of ~0.
    try std.testing.expect(@abs(sum) < 5.0);
}

test "sampleToUint matches lossless grid values despite dither" {
    // Integer-grid values (k / maxval) must survive the dither: the
    // reconstruction error (~3e-5) is far below the dither margin
    // (0.5 - 0.49219).
    var k: u32 = 0;
    while (k <= 255) : (k += 1) {
        const v = @as(f32, @floatFromInt(k)) * (1.0 / @as(f32, 255.0));
        var y: usize = 0;
        while (y < 34) : (y += 7) {
            var x: usize = 0;
            while (x < 34) : (x += 5) {
                const got = sampleToUint(v, 255.0, 8, x, y, 0);
                try std.testing.expectEqual(k, got);
            }
        }
    }
    // 16-bit: no dither, plain NearestInt(clamp(v*mul)).
    try std.testing.expectEqual(@as(u32, 65535), sampleToUint(1.0, 65535.0, 16, 0, 0, 0));
    try std.testing.expectEqual(@as(u32, 0), sampleToUint(-1.0, 65535.0, 16, 0, 0, 0));
    try std.testing.expectEqual(@as(u32, 0), sampleToUint(std.math.nan(f32), 255.0, 8, 3, 4, 2));
}
